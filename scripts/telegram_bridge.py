_SYS_BUDGET_TOK = int(os.environ.get("SKC_BRIDGE_SYS_BUDGET", "9000"))


def _est(s: str) -> int:
    return len(s) // _CHARS_PER_TOK + 1


def _fit_messages(chat_key: str, user_text: str, mem_block: str = "",
                  tools: list | None = None) -> list:
    """Capped system (+ live memory) + recent history that fits + new message.

    ``tools`` is the per-turn tool list actually sent this turn (defaults to the
    full cache) so the history budget reflects the real tool-schema cost.
    """
    turn_tools = _TOOLS_CACHE if tools is None else tools
    # Truncate the soul prompt to budget, then ALWAYS append the operating-facts
    # guardrail (model identity + no-fabrication rule) so it can't be cut off.
    system = SYSTEM[: _SYS_BUDGET_TOK * _CHARS_PER_TOK] + _OPERATING_FACTS
    if mem_block:
        system = system + "\n\n" + mem_block
    msgs = [{"role": "system", "content": system}]
    tool_cost = _est(json.dumps(turn_tools)) if turn_tools else 0
    avail = CTX_TOKENS - MAX_TOKENS - _MARGIN - tool_cost - _est(system) - _est(user_text)
    kept: list = []
    acc = 0
    for m in reversed(_history.get(chat_key, [])):
        t = _est(m.get("content") or "")
        if acc + t > avail:
            break
        kept.insert(0, m)
        acc += t
    msgs.extend(kept)
    msgs.append({"role": "user", "content": user_text})
    return msgs


def _call(msgs: list, with_tools: bool = True, *, url: str | None = None,
          model: str | None = None, context_key: str = "",
          tools: list | None = None) -> tuple[dict, str | None]:
    """One backend round-trip. Returns ``(assistant message dict, concrete_model)``.

    ``concrete_model`` is the backend's top-level ``response["model"]`` — CRITICAL
    for rating attribution: when routing via sk-auto through the gateway, the model
    that actually answered (ornith-1.0-9b / claude-opus-4-8 / the VL model) comes
    back here, not in the request. Callers fall back to the resolved backend model
    name when it's omitted.

    `url`/`model` default to the static LLM_URL/LLM_MODEL but are overridden per
    chat by the skmodels resolution. `context_key` (e.g. "chat:<id>") is attached
    as the `x-sk-context` header so a gateway backend routes per-chat itself
    (harmless to a direct backend, which ignores the header). `tools` is the
    per-turn tool list to advertise (defaults to the full _TOOLS_CACHE)."""
    call_url = url or LLM_URL
    call_model = model or LLM_MODEL
    turn_tools = _TOOLS_CACHE if tools is None else tools
    payload = {"model": call_model, "messages": msgs, "max_tokens": MAX_TOKENS}
    if with_tools and turn_tools:
        payload["tools"] = turn_tools
        payload["tool_choice"] = "auto"
    body = json.dumps(payload).encode()
    headers = {"Content-Type": "application/json"}
    if context_key:
        headers["x-sk-context"] = context_key
    req = urllib.request.Request(call_url, data=body, headers=headers)
    out = json.loads(urllib.request.urlopen(req, timeout=180).read())
    return out["choices"][0]["message"], out.get("model")


def _run_tool_loop(msgs: list, chat_id: str = "", *, url: str | None = None,
                   model: str | None = None,
                   tools: list | None = None) -> tuple[str, str | None]:
    """Drive the qwen3.6 tool-calling loop: call → dispatch MCP → feed back.

    Returns ``(reply text, concrete_model)`` — the concrete model is the one the
    LAST backend round-trip reported (``response["model"]``), so rating rows can be
    attributed to the model that actually produced the answer (matters under sk-auto
    routing where easy→ornith / hard→opus / image→VL).

    ``tools`` is the per-turn tool subset to advertise (defaults to the full
    _TOOLS_CACHE); dispatch itself can still reach any indexed tool the model
    names, so the subset only shapes what the model is offered."""
    context_key = _chat_context_key(chat_id) if chat_id else ""
    concrete_model: str | None = None
    for _round in range(MAX_TOOL_ROUNDS):
        msg, concrete_model = _call(msgs, with_tools=True, url=url, model=model,
                    context_key=context_key, tools=tools)
        calls = msg.get("tool_calls") or []
        if not calls:
            return (msg.get("content") or "").strip(), concrete_model
        # Append the assistant turn that requested the tools, then each result.
        msgs.append({"role": "assistant", "content": msg.get("content") or "",
                     "tool_calls": calls})
        for tc in calls:
            fn = tc.get("function", {})
            name = fn.get("name", "")
            try:
                args = json.loads(fn.get("arguments") or "{}")
            except json.JSONDecodeError:
                args = {}
            # Inject delivery context for tools that send media back to the chat —
            # the model never sees the chat_id; the bridge owns routing.
            if name in _DELIVERY_TOOLS and chat_id:
                args["deliver_chat_id"] = chat_id
            log.info("tool-call: %s(%s)", name, json.dumps(args)[:160])
            result = _ROUTER.dispatch(name, args)
            msgs.append({"role": "tool", "tool_call_id": tc.get("id", ""),
                         "name": name, "content": result[:6000]})
    # Ran out of rounds — ask for a final answer without tools.
    final, concrete_model = _call(msgs, with_tools=False, url=url, model=model,
                                  context_key=context_key)
    return (final.get("content") or "").strip(), concrete_model


def _strip_think(text: str) -> str:
    """Remove <think>…</think> reasoning blocks (Qwen abliterated emits them, often
    empty) from a reply. Drops everything up to the last </think>, then any stray
    open/close think tags. Never touches a reply that has none."""
    if not text:
        return text
    if "</think>" in text:
        text = text.rsplit("</think>", 1)[-1]
    text = _re.sub(r"</?think>", "", text)
    return text.strip()


def _llm(chat_key: str, user_text: str) -> tuple[str, str | None]:
    import urllib.error

    mem_block = ""
    try:
        mem_block = _MEM.inject(chat_key, user_text, router=_ROUTER)
    except Exception:
        log.debug("memory inject failed", exc_info=True)
    # Per-turn tool curation (lazy mode) — narrow the exposed toolset to what
    # this message likely needs; no-op (full cache) when SKC_BRIDGE_LAZY_TOOLS=0.
    turn_tools = _curate_turn_tools(user_text)
    msgs = _fit_messages(chat_key, user_text, mem_block=mem_block, tools=turn_tools)
    # Per-chat model routing: resolve the backend for this chat (honors /model
    # toggle on chat:<id>) and attach the x-sk-context header downstream.
    url, model = _resolve_backend_for_chat(chat_key)
    ctx_key = _chat_context_key(chat_key)
    concrete_model: str | None = None
    try:
        reply, concrete_model = _run_tool_loop(msgs, chat_id=chat_key, url=url,
                                               model=model, tools=turn_tools)
    except urllib.error.HTTPError as e:
        if e.code == 400:  # context overflow — retry minimal, no tools
            log.warning("400 from backend; retrying system+message only (no tools)")
            sys_only = [m for m in msgs if m["role"] == "system"]
            sys_only.append({"role": "user", "content": user_text})
            msg, concrete_model = _call(sys_only, with_tools=False, url=url,
                                        model=model, context_key=ctx_key)
            reply = (msg.get("content") or "").strip()
        else:
            raise
    # Strip <think>…</think> reasoning blocks the abliterated Qwen emits (incl. the
    # empty "<think>\n\n</think>" prefix) so they never leak into chat/voice/memory.
    reply = _strip_think(reply)
    # Concrete answering model for rating attribution: prefer what the backend
    # actually served (response["model"]); fall back to the resolved backend model.
    concrete_model = concrete_model or model
    _history[chat_key].append({"role": "user", "content": user_text})
    _history[chat_key].append({"role": "assistant", "content": reply})
    # Persist the interaction into the agent's living memory.
    try:
        _MEM.store(chat_key, user_text, reply)
    except Exception:
        log.debug("interaction store failed", exc_info=True)
    return reply, concrete_model


def _fetch_gateway_models() -> dict:
    """GET SKGateway's served-model list. Fail-soft: any error returns {}.

    Backs `/model`'s live catalog (skchat.agent_model.list_choices' `models`
    section). Mirrors daemon.py's `_fetch_gateway_models`, reading the bridge's
    own gateway env (`SKC_BRIDGE_GATEWAY_URL` / `_GATEWAY_URL`) instead."""
    root = (_GATEWAY_URL or "http://localhost:18780/v1").rstrip("/")
    if not root.endswith("/v1"):
        root = root + "/v1"
    url = root + "/models"
    try:
        with urllib.request.urlopen(url, timeout=2) as resp:  # noqa: S310
            parsed = json.loads(resp.read().decode())
            return parsed if isinstance(parsed, dict) else {}
    except Exception as exc:
        log.debug("model command: gateway model fetch failed (%s): %s", url, exc)
        return {}


def _skos_roles() -> list:
    """Role names from the skos.models registry. Fail-soft: [] on any error,
    including when skos isn't importable in this bridge's environment."""
    if _skmodels is None:
        return []
    try:
        return list((_skmodels.list_roles() or {}).keys())
    except Exception:
        log.debug("model command: skos.models.list_roles failed", exc_info=True)
        return []


def _handle_model_command(chat_id, text: str) -> str | None:
    """Handle the `/model` slash command for live model switching.

    Returns the reply text to send (and the caller then skips the LLM), or None
    when *text* is not a /model command.

      /model                     -> list roles + models (skchat.agent_model's
                                     dynamic catalog), current selection marked
      /model list                -> same
      /model <role-or-model-id>  -> set the shared PER-AGENT selection
                                     (skchat.agent_model), honored on every
                                     surface (app, voice, this bridge)
      /model pin <role>          -> pin THIS CHAT to <role> (skos.models
                                     `contexts: chat:<id>`); a Telegram-only,
                                     highest-precedence override, unchanged
                                     from before unification

    See docs/superpowers/specs/2026-07-25-unified-reply-model-selection-design.md.
    """
    stripped = text.strip()
    # Accept "/model", "/model@seaBird_Opus_bot" (group @-mention form), args after.
    parts = stripped.split()
    head = parts[0].split("@", 1)[0].lower() if parts else ""
    if head != "/model":
        return None
    rest = [p.strip().lower() for p in parts[1:]]
    arg = rest[0] if rest else ""

    from skchat.agent_model import classify, get_selection, list_choices, set_selection

    catalog = list_choices(gateway_fetch=_fetch_gateway_models, roles_source=_skos_roles)
    roles = catalog["roles"]
    model_ids = [m.get("id") for m in catalog["models"] if m.get("id")]

    if arg in ("", "list", "status", "get"):
        sel = get_selection(AGENT_NAME)
        kind = classify(sel, set(roles))
        lines = [f"{AGENT}'s selection (all surfaces):", ""]
        lines.append("Roles:")
        for role in roles:
            mark = "  <- current" if kind == "role" and role == sel else ""
            lines.append(f"  {role}{mark}")
        lines.append("")
        lines.append("Models:")
        for mid in model_ids:
            mark = "  <- current" if kind == "model" and mid == sel else ""
            lines.append(f"  {mid}{mark}")
        lines.append("")
        pin = None
        if _skmodels is not None:
            try:
                pin = (_skmodels.list_contexts() or {}).get(_chat_context_key(chat_id))
            except Exception:
                log.debug("model command: list_contexts failed", exc_info=True)
        if pin:
            lines.append(f"this chat is PINNED to {pin} (wins over the selection above)")
            lines.append("")
        lines.append("Set the agent's selection: /model <role-or-model-id>")
        lines.append("Pin just this chat instead: /model pin <role>")
        return "\n".join(lines)

    if arg == "pin":
        role = rest[1] if len(rest) > 1 else ""
        if not role:
            return "usage: /model pin <role>   (e.g. /model pin sk-vision)"
        if _skmodels is None:
            return ("(chat pin unavailable, skos.models isn't importable in this "
                    "bridge's environment.)")
        _fresh_registry()  # reflect any external/synced changes in the roster
        backends = _skmodels.list_backends() or {}
        if role not in roles and role not in backends:
            valid = ", ".join(list(roles) + list(backends))
            return f"unknown model '{role}'. valid targets: {valid}"
        try:
            _skmodels.set_context(_chat_context_key(chat_id), role)
        except Exception:
            log.exception("skmodels set_context failed")
            return f"(failed to pin this chat to {role}, registry write error; check the bridge logs.)"
        b = _skmodels.resolve(context=_chat_context_key(chat_id))
        vis = " [vision]" if getattr(b, "vision", False) else ""
        log.info("chat pin: %s -> %s (%s)", _chat_context_key(chat_id), role, b.name)
        return (f"pinned this chat to {role} -> {b.name} ({b.model}){vis}. "
                "Replies here now route there (overrides the agent selection).")

    # A swap request: set the shared per-agent selection.
    try:
        set_selection(AGENT_NAME, arg, valid_roles=set(roles), valid_models=set(model_ids))
    except ValueError:
        valid = ", ".join(list(roles) + model_ids)
        return f"unknown model '{arg}'. valid targets: {valid}"
    kind = classify(arg, set(roles))
    log.info("agent selection: %s -> %s (%s)", AGENT_NAME, arg, kind)
    return (f"switched {AGENT}'s selection to {arg} ({kind}). Applies on every "
            "chat/surface, unless this chat is pinned (see /model pin).")


# ── /code command: DORMANT autocode dispatch (Fable roadmap R8) ────────────── #
# A flag-gated, allowlisted Telegram entry to the autocode engine
# (skharness.autocode). It ships DORMANT and SAFE so that merging it cannot
# affect the running bots: the whole handler is gated on SKC_BRIDGE_CODE_ENABLED
# (default OFF) and an explicit allowlist SKC_BRIDGE_CODE_ALLOWED_IDS (comma-
# separated telegram user/chat ids; EMPTY = nobody). With the flag off, or from a
# non-allowlisted caller, `/code` only replies with a short refusal and NEVER
# touches the engine. Default mode is `direct` (DirectExecutor: one sandboxed
# run, no grade, no merge); a leading `gated` keyword selects the full loop
# (EngineeringExecutor). The telegram binding NEVER enables automerge: it loads
# config read-only and never adds a repo to config.automerge_repos or sets
# repo.automerge, so even a gated finalize is PR-only here (spec section 5.4 +
# guardrails G1/G2). Chef sets the flag + allowlist id later, a deploy step;
# nothing here turns it on. See
# docs/superpowers/specs/2026-07-25-autocode-toggle-and-integration.md.
# Env flags are read at call time (not import) so a deploy toggle takes effect
# on the next message with no restart, and so tests can set them per-case.
def _code_enabled() -> bool:
    """The DORMANT master switch. Off (default) => /code does nothing but refuse."""
    return os.environ.get("SKC_BRIDGE_CODE_ENABLED", "").strip().lower() in (
        "1", "true", "yes", "on")


def _code_allowed_ids() -> set:
    """Allowlisted telegram user/chat ids (SKC_BRIDGE_CODE_ALLOWED_IDS). An empty
    or unset value is the intentional default: nobody may dispatch."""
    raw = os.environ.get("SKC_BRIDGE_CODE_ALLOWED_IDS", "")
    return {p.strip() for p in raw.split(",") if p.strip()}


def _code_default_repo() -> str:
    """The repo to target when a /code command names none (SKC_BRIDGE_CODE_DEFAULT_REPO)."""
    return os.environ.get("SKC_BRIDGE_CODE_DEFAULT_REPO", "").strip()


def _code_caller_allowed(user_id, chat_id) -> bool:
    """True only when the sender's user id OR the chat id is on the allowlist.
    Empty allowlist (the default) => always False (fail-closed)."""
    allowed = _code_allowed_ids()
    if not allowed:
        return False
    candidates = {str(c) for c in (user_id, chat_id) if c is not None}
    return bool(candidates & allowed)


def _parse_code_command(text: str):
    """Parse ``/code [gated|direct] [repo=<name>] <task text>``.

    Returns ``(mode, repo_or_None, task)`` where mode is the string ``"direct"``
    (default) or ``"gated"``, or None when *text* is not a /code command. Accepts
    the group @-mention form (``/code@seaBird_Opus_bot ...``). repo falls back to
    SKC_BRIDGE_CODE_DEFAULT_REPO when not named with ``repo=``.
    """
    stripped = (text or "").strip()
    parts = stripped.split()
    head = parts[0].split("@", 1)[0].lower() if parts else ""
    if head != "/code":
        return None
    rest = parts[1:]
    mode = "direct"                      # per spec 5.4: telegram default is direct
    if rest and rest[0].lower() in ("gated", "direct"):
        mode = rest[0].lower()
        rest = rest[1:]
    repo = _code_default_repo() or None
    task_words: list[str] = []
    for w in rest:
        if w.lower().startswith("repo=") and len(w) > len("repo="):
            repo = w.split("=", 1)[1]
        else:
            task_words.append(w)
    return mode, repo, " ".join(task_words).strip()


def _run_autocode(repo_name: str, task: str, mode: str, *, chat_id=None) -> str:
    """Invoke the autocode engine IN-PROCESS for one task (library binding, spec
    5.4). Returns a summary string for the chat. Only reached from
    ``_handle_code_command`` after the flag + allowlist gate, so a disabled bridge
    never gets here.

    DORMANT-safe by construction: config is loaded READ-ONLY and this function
    never enables automerge (it never sets repo.automerge and never appends to
    config.automerge_repos). The engine merges only when repo.automerge AND
    repo.name in config.automerge_repos, so a gated finalize from telegram is
    PR-only. `direct` routes to DirectExecutor (one run, no gate, and its own G1
    guard forbids merge); `gated` routes to EngineeringExecutor (the full loop).
    """
    from skharness.autocode import config as _ac_config
    from skharness.autocode import digest as _ac_digest
    from skharness.autocode import journal as _ac_journal
    from skharness.autocode.direct import DirectExecutor
    from skharness.autocode.engineering import EngineeringExecutor
    from skharness.autocode.harness import build_harness
    from skharness.autocode.types import QualityMode, WorkItem

    cfg = _ac_config.load()
    repo_spec = cfg.repo(repo_name)
    if repo_spec is None:
        return (f"code dispatch: repo '{repo_name}' is not configured in "
                "autopilot.yaml (repo_map); refusing.")

    gated = mode == QualityMode.GATED.value
    executor_cls = EngineeringExecutor if gated else DirectExecutor
    kind = "engineering" if gated else "engineering-direct"
    ref = f"telegram/{chat_id if chat_id is not None else 'code'}-{int(time.time())}"
    item = WorkItem(
        kind=kind, ref=ref, source="telegram", repo=repo_name,
        payload={"title": task[:80], "description": task, "acceptance": [],
                 "tags": [f"repo:{repo_name}"], "unblocked": True,
                 "verdict": "valid"})

    from skcapstone.coordination import Board
    from skcapstone.mcp_tools._helpers import _shared_root

    board = Board(_shared_root())
    handle = _ac_journal.handle(ref)
    executor = executor_cls(cfg, board, handle, _ac_digest)
    harness = build_harness(cfg, cfg.harness)

    result = executor.run(item, harness)
    executor.finalize(item, result)      # PR + review decision; never automerges here

    marker = "" if gated else " UNGATED, review before merge"
    return (f"code dispatch [{mode}] on {repo_name}: {ref}\n"
            f"score={result.score} passed={result.passed} mode={result.mode}"
            f"{marker}\n{result.notes}")


def _handle_code_command(chat_id, user_id, text: str):
    """Handle the `/code` slash command (DORMANT). Returns the reply text to send
    (and the caller skips the LLM), or None when *text* is not a /code command.

    Order of gates, all fail-closed: (1) SKC_BRIDGE_CODE_ENABLED must be on, else
    a short 'disabled' reply and the engine is NOT touched; (2) the caller must be
    allowlisted, else a refusal and the engine is NOT touched; (3) a repo must
    resolve and the task must be non-empty. Only then is ``_run_autocode`` called.
    """
    parsed = _parse_code_command(text)
    if parsed is None:
        return None
    mode, repo, task = parsed
    if not _code_enabled():
        return ("code dispatch is disabled on this bridge. (it ships dormant; set "
                "SKC_BRIDGE_CODE_ENABLED to turn it on.)")
    if not _code_caller_allowed(user_id, chat_id):
        return "code dispatch: you are not on the allowlist for /code. request refused."
    if not repo:
        return ("code dispatch: no repo. use `/code repo=<name> <task>` or set "
                "SKC_BRIDGE_CODE_DEFAULT_REPO.")
    if not task:
        return "usage: /code [gated] [repo=<name>] <task description>"
    try:
        return _run_autocode(repo, task, mode, chat_id=chat_id)
    except Exception:
        log.exception("code dispatch failed")
        return f"code dispatch: engine error running the task on {repo} (see bridge logs)."


# Voice-reply policy: "voice" (default) = speak back only when spoken to;
# "always" = voice every reply; "off" = never send voice.
VOICE_REPLY = os.environ.get("SKC_BRIDGE_VOICE_REPLY", "voice").strip().lower()


def _extract_voice(u: dict) -> str | None:
    """Return the file_id of a voice/audio note in a raw update, else None."""
    msg = u.get("message") or u.get("edited_message") or {}
    v = msg.get("voice") or msg.get("audio")
    return v.get("file_id") if isinstance(v, dict) else None


def _handle_reaction(u: dict) -> None:
    """A user reacted to one of the bot's images/videos → record it as a rating.

    👎=1 🤷=2 👍=3 ❤️=4 🔥=5 (skchat.rating_reactions.EMOJI_SCORE); other emojis
    ignored. Anonymous/channel reactions (no user) are dropped.
    """
    mr = u.get("message_reaction") or {}
    if not mr.get("user"):
        return
    new = mr.get("new_reaction") or []
    if not new:
        return
    emoji = (new[-1] or {}).get("emoji")
    chat_id = (mr.get("chat") or {}).get("id")
    message_id = mr.get("message_id")
    try:
        from skchat import rating_reactions as _RR
        score = _RR.record_telegram_reaction(chat_id, message_id, emoji)
        if score is not None:
            log.info("reaction → rating: chat=%s msg=%s emoji=%s score=%d",
                     chat_id, message_id, emoji, score)
    except Exception:
        log.debug("reaction handling failed", exc_info=True)


async def main() -> None:
    adapter = TelegramAdapter(config={"bot_token": TOKEN})
    # Receive emoji reactions (excluded from getUpdates by default) so the image
    # rating loop works — see _handle_reaction.
    adapter._allowed_updates = ["message", "edited_message", "message_reaction",
                                "callback_query"]
    hub = AdapterHub(outbound_adapter=adapter, resolve_fqid=lambda ident: "chef@skworld.io")
    _init_brain()
    log.info("Telegram bridge live as %s — polling getUpdates", AGENT)
    # Tell systemd (Type=notify drop-in) startup is done; a no-op when
    # NOTIFY_SOCKET is unset (not running under that unit, or in tests).
    _bw.sd_notify("READY=1")
    failures = _bw.PollFailureTracker(threshold=WEDGE_THRESHOLD)
    while True:
        try:
            # Seatbelt: a wedged httpx connection pool (observed after a Telegram
            # ConnectTimeout) can make _poll() hang forever, silently killing the
            # bot while systemd still sees it "active". Bound every poll so a hang
            # raises TimeoutError → caught below → loop retries instead of wedging.
            updates = await asyncio.wait_for(adapter._poll(), timeout=POLL_TIMEOUT)
        except Exception:
            log.exception("poll failed or timed out (consecutive %d/%d)",
                          failures.consecutive + 1, failures.threshold)
            if failures.on_failure():
                msg = (f"telegram bridge {AGENT} wedged after {failures.threshold} "
                       f"failures, exiting for restart")
                log.error(msg)
                _bw.sk_alert(msg)
                sys.exit(1)
            await asyncio.sleep(2)
            continue
        failures.on_success()
        # A successful poll cycle -- heartbeat so systemd's WatchdogSec doesn't
        # kill us; no-op when NOTIFY_SOCKET is unset.
        _bw.sd_notify("WATCHDOG=1")
        try:
            for u in updates:
                # Emoji reaction on a bot image/video → rating loop (no reply).
                if u.get("message_reaction"):
                    _handle_reaction(u)
                    continue
                # 👍/👎 inline-button press on a bot reply → answer rating (no reply).
                if u.get("callback_query"):
                    _handle_callback(TOKEN, u["callback_query"])
                    continue
                m = adapter._normalize(u)
                incoming = m.text if (m and getattr(m, "text", None)) else None
                is_voice = False

                # Inbound voice note: download → Whisper STT → text.
                if not incoming:
                    file_id = _extract_voice(u)
                    if file_id:
                        audio = _tg_get_file_bytes(TOKEN, file_id)
                        if audio:
                            try:
                                incoming = _VOICE.transcribe(audio, "voice.ogg")
                                is_voice = True
                                log.info("voice transcribed (%d chars): %s",
                                         len(incoming), incoming[:80])
                            except Exception:
                                log.exception("STT failed")

                # Inbound forwarded media (photo/video/audio/document): download to
                # the scratch cache so the `ingest` tool can process the file, then
                # surface its path (+ any caption) to the model so it can file/lens it.
                if not incoming or _extract_media(u):
                    media = _extract_media(u)
                    if media and media[0]:
                        file_id, kind, ext, caption = media
                        blob = _tg_get_file_bytes(TOKEN, file_id)
                        if blob:
                            path = _save_ingest_tmp(blob, ext)
                            lens = " For an image / X-post you can then say 'lens this'." \
                                if kind in ("photo", "document") else ""
                            hint = (f"[Forwarded {kind} saved to {path} — to file it into the "
                                    f"realm wiki, call the `ingest` tool with that exact path.{lens}]")
                            incoming = f"{caption}\n\n{hint}" if caption else \
                                f"(Chef forwarded a {kind}, no caption.)\n{hint}"
                            log.info("forwarded %s saved → %s (caption=%r)", kind, path, caption[:40])
                if not incoming:
                    continue

                chat_id = m.room_id if m else (
                    (u.get("message") or u.get("edited_message") or {}).get("chat", {}).get("id"))
                if chat_id is None:
                    continue

                if m and getattr(m, "text", None):
                    try:
                        hub.handle_inbound(m)
                    except Exception:
                        log.exception("handle_inbound failed (continuing)")

                # Slash-command: live per-chat model swap. Handled locally (no LLM,
                # no voice) — replies with the roster / confirms the toggle.
                cmd_reply = _handle_model_command(chat_id, incoming)
                if cmd_reply is not None:
                    try:
                        _send_html(TOKEN, chat_id, cmd_reply)
                        log.info("replied (/model) to %s", chat_id)
                    except Exception:
                        log.exception("send failed (/model)")
                    continue

                # Slash-command: DORMANT autocode dispatch (flag-gated + allowlisted).
                # Off by default (SKC_BRIDGE_CODE_ENABLED unset) => a short refusal,
                # no engine, no LLM. Additive; changes no other bridge behavior.
                from_user = ((u.get("message") or u.get("edited_message") or {})
                             .get("from") or {})
                code_reply = _handle_code_command(chat_id, from_user.get("id"), incoming)
                if code_reply is not None:
                    try:
                        _send_html(TOKEN, chat_id, code_reply)
                        log.info("replied (/code) to %s", chat_id)
                    except Exception:
                        log.exception("send failed (/code)")
                    continue

                concrete_model: str | None = None
                try:
                    with _Typing(TOKEN, chat_id):   # 'typing…' until the reply is ready
                        reply, concrete_model = _llm(str(chat_id), incoming)
                except Exception:
                    log.exception("LLM failed")
                    reply = f"({AGENT}) sorry — my language backend hiccuped, try again."

                # Voice reply when spoken to (or always), plus the text transcript.
                want_voice = VOICE_REPLY == "always" or (is_voice and VOICE_REPLY != "off")
                if want_voice:
                    try:
                        if _send_voice(TOKEN, chat_id, reply):
                            log.info("replied (voice) to %s", chat_id)
                    except Exception:
                        log.exception("voice send failed")
                try:
                    msg_id = _send_html(TOKEN, chat_id, reply, rating_buttons=True)
                    log.info("replied (HTML) to %s", chat_id)
                    # Record which concrete model answered this message so a later
                    # 👍/👎 press can attribute the score (opt-in; flag-gated).
                    if _RATING_BUTTONS and msg_id and concrete_model and _ratings is not None:
                        try:
                            _ratings.record_send(str(chat_id), str(msg_id), concrete_model)
                        except Exception:
                            log.debug("record_send failed", exc_info=True)
                except Exception:
                    log.exception("send failed")
        except Exception:
            log.exception("poll loop error (continuing)")
        await asyncio.sleep(2)


if __name__ == "__main__":
    asyncio.run(main())
